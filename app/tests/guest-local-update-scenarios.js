const fs = require('fs')
const path = require('path')

const root = path.resolve(__dirname, '..')
const main = fs.readFileSync(path.join(root, 'main.min.js'), 'utf8')
const preload = fs.readFileSync(path.join(root, 'preload.min.js'), 'utf8')
const noUpdates = fs.readFileSync(path.join(root, 'main.no-updates.js'), 'utf8')
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'))

function assert(condition, message) {
  if (!condition) throw new Error(message)
}

assert(pkg.version === '1.5.22', 'expected KAIZEN 1.5.22')
assert(main.includes("ensurePersistentKaizenStorage"), 'persistent storage bootstrap missing')
assert(main.includes("KAIZEN-Logistica"), 'persistent logistics root missing')
assert(main.includes("fsp.symlink(_0xpersistent,_0xlegacy,process.platform==='win32'?'junction':'dir')"), 'persistent junction creation missing')
assert(main.includes("guestDiscoverZipPackages"), 'ZIP package discovery missing')
assert(main.includes("browserprofiles?data"), 'case-insensitive resources.zip profile discovery missing')
assert(main.includes("guestExtractBundleProfile"), 'selective resources.zip extraction missing')
assert(main.includes("guestApplyLocalUpdates"), 'bulk local update application missing')
assert(main.includes("guestRecoverAccidentalResourcesProfile"), 'accidental resources profile recovery missing')
assert(main.includes("guestFindNestedDataRoots"), 'recursive data-root discovery missing')
assert(main.includes("guestExtractAndRecoverResourcesZip"), 'resources.zip fallback extraction missing')
assert(main.includes("guestAtomicAdoptProfileDir"), 'atomic recovered-profile adoption missing')
assert(main.includes("String(_0xzipName||'').toLowerCase()==='resources.zip'"), 'resources.zip must not fall back to a fake profile')
assert(main.includes("ipcMain.handle('guest-local-refresh'"), 'guest-local-refresh IPC missing')
assert(main.includes("ipcMain.handle('guest-local-import-bundle'"), 'resources.zip import IPC missing')
assert(main.includes("ipcMain.handle('guest-local-folder-open'"), 'guest-local-folder-open IPC missing')
assert(main.includes("ipcMain.handle('guest-open-profile'"), 'guest-open-profile IPC missing')
