const fs = require('fs')
const path = require('path')

const root = path.resolve(__dirname, '..')
const main = fs.readFileSync(path.join(root, 'main.min.js'), 'utf8')
const preload = fs.readFileSync(path.join(root, 'preload.min.js'), 'utf8')
const noUpdates = fs.readFileSync(path.join(root, 'main.no-updates.js'), 'utf8')
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'))

function assert(condition, message) {
  if (!condition) throw new Error(message)
}

assert(pkg.version === '1.5.24', 'expected KAIZEN 1.5.24')
assert(main.includes("ensurePersistentKaizenStorage"), 'persistent storage bootstrap missing')
assert(main.includes("KAIZEN-Logistica"), 'persistent logistics root missing')
assert(main.includes("guestListInstalledProfiles"), 'installed-only profile listing missing')
assert(main.includes("ipcMain.handle('guest-installed-profiles'"), 'installed-only IPC missing')
assert(main.includes("ipcMain.handle('guest-installed-folder-open'"), 'installed folder IPC missing')
assert(main.includes("opening installed profile"), 'installed-only open marker missing')
assert(main.includes("Este perfil no está cargado físicamente en esta PC."), 'missing installed-profile guard')
assert(!main.includes("const _0xrecovery=await guestRecoverAccidentalResourcesProfile();"), 'startup must not auto-recover/import resources')
assert(preload.includes("guest-installed-profiles"), 'installed-only UI missing')
assert(preload.includes("guest-installed-folder-open"), 'installed folder button missing')
assert(preload.includes("👤 Modo invitado · perfiles cargados"), 'stable guest title missing')
assert(preload.includes("✓ Cargado localmente"), 'local loaded status missing')
assert(preload.includes("↻ Recargar"), 'safe reload button missing')
assert(!preload.includes("📦 Importar resources.zip"), 'resources.zip import must be removed from guest UI')
assert(!preload.includes("📂 Importar carpeta"), 'folder import must be removed from guest UI')
assert(!preload.includes("🔄 Actualizar todo"), 'bulk update must be removed from guest UI')
assert(!preload.includes("guest-local-import-bundle"), 'ZIP import bridge must not be exposed')
assert(!preload.includes("guest-local-import-folder"), 'folder import bridge must not be exposed')
assert(!preload.includes("guest-local-refresh"), 'update/scan bridge must not be exposed to guest UI')
assert(!preload.includes("localStorage.getItem('token')"), 'guest UI must not read user token')
assert(noUpdates.includes("autoUpdater.checkForUpdates = async () => null"), 'application updater must remain disabled')
assert(noUpdates.includes("autoUpdater.downloadUpdate = async () => []"), 'application updater download must remain disabled')

console.log('guest-local-update-scenarios: OK')
